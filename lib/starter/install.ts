function layoutFile(s: StarterSettings): string {
  return `import type { Metadata } from "next";
import { Inter, Geist_Mono } from "next/font/google";

import "./globals.css";
import { Providers } from "@/components/providers";

// Inter with its optical-size axis: Fluid Functionalism animates a label's
// weight together with opsz, so it gets bolder without getting wider. Without
// the axis (or with a static Inter) weight changes shift the layout.
const inter = Inter({ subsets: ["latin"], axes: ["opsz"], variable: "--font-sans" });
const mono = Geist_Mono({ subsets: ["latin"], variable: "--font-mono" });

export const metadata: Metadata = {
  title: "My app",
  description: "Built with Fluid Functionalism.",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={\`\${inter.variable} \${mono.variable} font-sans antialiased\`}
      // The accent (${ACCENT_PRESETS[s.accent].label}): focus rings, the switch track and every other
      // accented detail read --fluid-accent. Change it here.${accentCss(s.accent, null).startsWith("light-dark") ? `
      // light-dark() picks the light or dark shade from the theme's color-scheme.` : ""}
      style={{ "--fluid-accent": "${accentCss(s.accent, null)}" } as React.CSSProperties}
    >
      <body>
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
`;
}

function providersFile(s: StarterSettings): string {
  const set = s.icons === "lucide" ? null : ICON_SETS[s.icons];
  const lines = [
    `"use client";`,
    ``,
    settingsComment(s, "starter"),
    `// Change a value below and every component follows.`,
    ``,
    `import { ThemeProvider } from "@/components/theme-provider";`,
    `import { FluidProvider } from "@/lib/fluid-provider";`,
  ];
  if (set) lines.push(`import { ${set.exportName} } from "@/lib/${set.item}";`);
  lines.push(
    ``,
    `export function Providers({ children }: { children: React.ReactNode }) {`,
    `  return (`,
    `    <ThemeProvider defaultTheme="${s.theme}">`,
    `      <FluidProvider shape="${s.shape}" size="${s.size}"${set ? ` icons={${set.exportName}}` : ""}>`,
    `        {children}`,
    `      </FluidProvider>`,
    `    </ThemeProvider>`,
    `  );`,
    `}`,
    ``,
  );
  return lines.join("\n");
}

function themeProviderFile(): string {
  return `"use client";

import * as React from "react";
import { ThemeProvider as NextThemesProvider, useTheme } from "next-themes";

// next-themes on the class strategy the theme tokens read (.dark on <html>),
// plus a D shortcut that flips between light and dark.
export function ThemeProvider({
  children,
  ...props
}: React.ComponentProps<typeof NextThemesProvider>) {
  return (
    <NextThemesProvider
      attribute="class"
      defaultTheme="system"
      enableSystem
      disableTransitionOnChange
      {...props}
    >
      <ThemeHotkey />
      {children}
    </NextThemesProvider>
  );
}

function ThemeHotkey() {
  const { resolvedTheme, setTheme } = useTheme();

  React.useEffect(() => {
    function onKeyDown(event: KeyboardEvent) {
      if (event.defaultPrevented || event.repeat) return;
      if (event.metaKey || event.ctrlKey || event.altKey) return;
      if (event.key.toLowerCase() !== "d") return;
      const target = event.target;
      if (
        target instanceof HTMLElement &&
        (target.isContentEditable || ["INPUT", "TEXTAREA", "SELECT"].includes(target.tagName))
      ) {
        return;
      }
      setTheme(resolvedTheme === "dark" ? "light" : "dark");
    }
    window.addEventListener("keydown", onKeyDown);
    return () => window.removeEventListener("keydown", onKeyDown);
  }, [resolvedTheme, setTheme]);

  return null;
}
`;
}

function pageFile(): string {
  return `"use client";

import { useState, useSyncExternalStore } from "react";
import { useTheme } from "next-themes";
import { SidebarProvider, SidebarInset } from "@/components/ui/sidebar";
import { Select, SelectTrigger, SelectContent, SelectItem } from "@/components/ui/select";
import { CheckboxGroup, CheckboxItem } from "@/components/ui/checkbox-group";
import { Button } from "@/components/ui/button";
import { AppSidebar } from "@/components/sidebar-app/app-sidebar";
import { SidebarInsetTopbar } from "@/components/sidebar-app/inset-topbar";
import { useShapeContext, type ShapeVariant } from "@/lib/shape-context";
import { useSizeContext, typeClass, type SizeVariant } from "@/lib/size-context";
import { SurfaceProvider } from "@/lib/surface-context";
import { fontWeights } from "@/lib/font-weight";
import { useIcons } from "@/lib/icon-context";
import { cn } from "@/lib/utils";

const THEMES = [
  { value: "system", label: "System" },
  { value: "light", label: "Light" },
  { value: "dark", label: "Dark" },
];
const SHAPES: { value: ShapeVariant; label: string }[] = [
  { value: "rounded", label: "Rounded" },
  { value: "pill", label: "Pill" },
];
const SIZES: { value: SizeVariant; label: string }[] = [
  { value: "default", label: "Default" },
  { value: "compact", label: "Compact" },
];
const TOPICS = ["Mentions", "Replies", "Weekly digest", "Product news"];

// The theme is only known in the browser (next-themes reads it after
// hydration), so the server renders the control with "system".
const subscribe = () => () => {};
function useMounted() {
  return useSyncExternalStore(subscribe, () => true, () => false);
}

export default function Page() {
  const { theme, setTheme } = useTheme();
  const { shape, setShape } = useShapeContext();
  const { size, setSize } = useSizeContext();
  const mounted = useMounted();
  const icons = useIcons();
  const [topics, setTopics] = useState<Set<number>>(new Set([0, 1]));

  const toggleTopic = (i: number) =>
    setTopics((prev) => {
      const next = new Set(prev);
      if (next.has(i)) next.delete(i);
      else next.add(i);
      return next;
    });

  return (
    <SidebarProvider>
      <AppSidebar />
      <SidebarInset>
        <SidebarInsetTopbar />
        <main className="flex flex-1 justify-center p-6">
          <div className="flex w-full max-w-xl flex-col gap-10 py-10">
            <header className="flex flex-col gap-2">
              <h1
                className={cn(typeClass("display", size), "text-foreground")}
                style={{ fontVariationSettings: fontWeights.semibold }}
              >
                Your app starts here
              </h1>
              <p className={cn(typeClass("body", size), "text-muted-foreground")}>
                Every Fluid Functionalism component is in components/ui, set to
                the choices you made on the site. Edit app/page.tsx to start
                building, and components/providers.tsx to change the defaults.
              </p>
            </header>

            <section className="flex flex-col gap-3">
              <h2
                className={cn(typeClass("subtitle", size), "text-foreground")}
                style={{ fontVariationSettings: fontWeights.semibold }}
              >
                Make it yours
              </h2>
              {/* bg-muted is surface 2: popups opened in here lift above it */}
              <SurfaceProvider value={2}>
                <div className="flex flex-col gap-1 rounded-xl bg-muted p-3">
                  <SettingRow label="Theme" hint="Press D to flip light and dark">
                    <Select value={mounted ? (theme ?? "system") : "system"} onValueChange={setTheme}>
                      <SelectTrigger variant="borderless" className="w-auto min-w-0" />
                      <SelectContent>
                        {THEMES.map((o, i) => (
                          <SelectItem key={o.value} value={o.value} index={i}>
                            {o.label}
                          </SelectItem>
                        ))}
                      </SelectContent>
                    </Select>
                  </SettingRow>
                  <SettingRow label="Radius">
                    <Select value={shape} onValueChange={(v) => setShape(v as ShapeVariant)}>
                      <SelectTrigger variant="borderless" className="w-auto min-w-0" />
                      <SelectContent>
                        {SHAPES.map((o, i) => (
                          <SelectItem key={o.value} value={o.value} index={i}>
                            {o.label}
                          </SelectItem>
                        ))}
                      </SelectContent>
                    </Select>
                  </SettingRow>
                  <SettingRow label="Size">
                    <Select value={size} onValueChange={(v) => setSize(v as SizeVariant)}>
                      <SelectTrigger variant="borderless" className="w-auto min-w-0" />
                      <SelectContent>
                        {SIZES.map((o, i) => (
                          <SelectItem key={o.value} value={o.value} index={i}>
                            {o.label}
                          </SelectItem>
                        ))}
                      </SelectContent>
                    </Select>
                  </SettingRow>
                </div>
              </SurfaceProvider>
            </section>

            <section className="flex flex-col gap-3">
              <h2
                className={cn(typeClass("subtitle", size), "text-foreground")}
                style={{ fontVariationSettings: fontWeights.semibold }}
              >
                Notify me about
              </h2>
              {/* One hover highlight glides between rows; checked neighbours merge */}
              <CheckboxGroup checkedIndices={topics}>
                {TOPICS.map((label, i) => (
                  <CheckboxItem
                    key={label}
                    index={i}
                    label={label}
                    checked={topics.has(i)}
                    onToggle={() => toggleTopic(i)}
                  />
                ))}
              </CheckboxGroup>
            </section>

            <div className="flex flex-wrap gap-2">
              <Button variant="primary" leadingIcon={icons.check}>
                Save
              </Button>
              <Button variant="tertiary" onClick={() => setTopics(new Set())}>
                Clear
              </Button>
            </div>
          </div>
        </main>
      </SidebarInset>
    </SidebarProvider>
  );
}

function SettingRow({
  label,
  hint,
  children,
}: {
  label: string;
  hint?: string;
  children: React.ReactNode;
}) {
  const { size } = useSizeContext();
  return (
    <div className="flex items-center justify-between gap-4 pl-2">
      <div className="flex flex-col">
        <span className={cn(typeClass("body", size), "text-foreground")}>{label}</span>
        {hint && <span className={cn(typeClass("caption", size), "text-muted-foreground")}>{hint}</span>}
      </div>
      {children}
    </div>
  );
}
`;
}

function fluidRootFile(s: StarterSettings): string {
  const set = s.icons === "lucide" ? null : ICON_SETS[s.icons];
  const lines = [
    `"use client";`,
    ``,
    settingsComment(s, "setup"),
    `// Wrap the root layout's children in <FluidRoot>, inside your theme provider.`,
    ``,
    `import { FluidProvider } from "@/lib/fluid-provider";`,
  ];
  if (set) lines.push(`import { ${set.exportName} } from "@/lib/${set.item}";`);
  lines.push(
    ``,
    `export function FluidRoot({ children }: { children: React.ReactNode }) {`,
    `  return (`,
    `    <FluidProvider shape="${s.shape}" size="${s.size}"${set ? ` icons={${set.exportName}}` : ""}>`,
    `      {children}`,
    `    </FluidProvider>`,
    `  );`,
    `}`,
    ``,
  );
  return lines.join("\n");
}

/** The app shell: the sidebar playground's default preset, written where the
 *  sidebar-app block puts the same two files. */
function shellFiles(s: StarterSettings): StarterFile[] {
  return generateSidebarPresetFiles({ ...DEFAULT_PRESET, flavor: s.base })
    .filter((f) => f.target !== "app/sidebar/page.tsx")
    .map((f) => {
      const target = f.target.replace("components/sidebar-preset/", "components/sidebar-app/");
      return {
        ...f,
        path: target,
        target,
        content: f.content.replaceAll("@/components/sidebar-preset/", "@/components/sidebar-app/"),
      };
    });
}

export function starterFiles(s: StarterSettings): StarterFile[] {
  return [
    { path: "app/layout.tsx", type: "registry:file", target: "app/layout.tsx", content: layoutFile(s) },
    { path: "app/page.tsx", type: "registry:page", target: "app/page.tsx", content: pageFile() },
    { path: "components/providers.tsx", type: "registry:file", target: "components/providers.tsx", content: providersFile(s) },
    { path: "components/theme-provider.tsx", type: "registry:file", target: "components/theme-provider.tsx", content: themeProviderFile() },
    ...shellFiles(s),
  ];
}

export function setupFiles(s: StarterSettings): StarterFile[] {
  return [
    { path: "components/fluid-root.tsx", type: "registry:file", target: "components/fluid-root.tsx", content: fluidRootFile(s) },
  ];
}

