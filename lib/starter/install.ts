// ---------------------------------------------------------------------------
// The starter: one registry item that turns a fresh `shadcn create` project
// into a Fluid Functionalism app with every component installed and the
// visitor's "Make them yours" settings applied. Pure functions only (they run
// in the /r/starter and /r/setup route handlers): settings in, registry item
// out. The routes resolve dependency names to flavored URLs.
//
// Two shapes of the same install:
//   - starter (registry:base, for `shadcn create`): components.json config,
//     the root layout (Inter with its opsz axis), providers, a home page in
//     the app shell, and the radius scale the components are drawn for.
//   - setup (registry:item, for `shadcn add` into an existing app): the
//     components and one FluidRoot wrapper; the app wires it in itself.
// ---------------------------------------------------------------------------

import { generateSidebarPresetFiles } from "@/lib/preset/sidebar-install";
import { DEFAULT_PRESET } from "@/lib/preset/sidebar-options";
import { starterSlug, type StarterSettings } from "./settings";
import { ACCENT_PRESETS, accentCss } from "@/lib/accent";

export const SITE = "https://www.fluidfunctionalism.com";

/** Registry items the starter leaves out: `sidebar-app` writes its own page
 *  route (/sidebar), and the starter generates the same shell files under
 *  the same names for its home page instead. */
const EXCLUDED = new Set(["sidebar-app"]);

const ICON_SETS: Record<Exclude<StarterSettings["icons"], "lucide">, { item: string; exportName: string }> = {
  tabler: { item: "icons-tabler", exportName: "tablerIcons" },
  phosphor: { item: "icons-phosphor", exportName: "phosphorIcons" },
  hugeicons: { item: "icons-hugeicons", exportName: "hugeiconsIcons" },
  untitledui: { item: "icons-untitledui", exportName: "untitleduiIcons" },
};

/** A file the starter writes. `registry:file` lands at its target as is,
 *  which is how the root layout and providers replace the template's. */
export interface StarterFile {
  path: string;
  type: "registry:file" | "registry:page" | "registry:component";
  target: string;
  content: string;
}

interface ManifestItem {
  name: string;
  type: string;
}

/** Every installable item, once. The Base UI twins (`*-base`) are reached
 *  through the flavored URL of their Radix name, never listed themselves,
 *  and of the icon sets only the chosen one installs (each pulls its own
 *  icon package). */
export function starterRegistryDeps(items: readonly ManifestItem[], s: StarterSettings): string[] {
  const chosenSet = s.icons === "lucide" ? null : ICON_SETS[s.icons].item;
  return items
    .map((i) => i.name)
    .filter(
      (name) =>
        !name.endsWith("-base") &&
        !EXCLUDED.has(name) &&
        (!name.startsWith("icons-") || name === chosenSet),
    );
}


export const SETTING_LABELS = {
  theme: { system: "System", light: "Light", dark: "Dark" },
  shape: { rounded: "Rounded", pill: "Pill" },
  size: { default: "Default", compact: "Compact" },
  icons: { lucide: "Lucide", tabler: "Tabler", phosphor: "Phosphor", hugeicons: "HugeIcons", untitledui: "Untitled UI" },
  base: { radix: "Radix", base: "Base UI" },
  accent: Object.fromEntries(Object.entries(ACCENT_PRESETS).map(([k, v]) => [k, v.label])) as {
    [K in keyof typeof ACCENT_PRESETS]: string;
  },
} as const;

/** "Base UI, rounded, default size, Untitled UI icons, system theme, blue
 *  accent". A custom accent (site-only, a hex) replaces the preset's name. */
export function describeSettings(s: StarterSettings, customAccent: string | null = null): string {
  return [
    SETTING_LABELS.base[s.base],
    SETTING_LABELS.shape[s.shape].toLowerCase(),
    `${SETTING_LABELS.size[s.size].toLowerCase()} size`,
    `${SETTING_LABELS.icons[s.icons]} icons`,
    `${SETTING_LABELS.theme[s.theme].toLowerCase()} theme`,
    `${customAccent ?? SETTING_LABELS.accent[s.accent].toLowerCase()} accent`,
  ].join(", ");
}

/** Header for the files that carry settings: where they came from, in words. */
function settingsComment(s: StarterSettings, kind: "starter" | "setup"): string {
  return `// Generated by ${SITE}/r/${kind}/${starterSlug(s)}.json\n// Settings: ${describeSettings(s)}.`;
}

