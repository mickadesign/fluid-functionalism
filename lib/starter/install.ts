/** shadcn's new-project CSS derives the radius scale from --radius (8, 10
 *  and 14px for md, lg, xl); the components are drawn on Tailwind's own
 *  scale (6, 8, 12px), where their nested radii stay concentric. */
const RADIUS_SCALE = {
  "radius-sm": "0.25rem",
  "radius-md": "0.375rem",
  "radius-lg": "0.5rem",
  "radius-xl": "0.75rem",
  "radius-2xl": "1rem",
  "radius-3xl": "1.5rem",
  "radius-4xl": "2rem",
};

type DepUrl = (dep: string, flavor: "flat" | "radix" | "base") => string;

function registryDepsFor(s: StarterSettings, items: readonly ManifestItem[], depUrl: DepUrl): string[] {
  return starterRegistryDeps(items, s).map((dep) => depUrl(dep, s.base));
}

export function buildStarterItem(s: StarterSettings, items: readonly ManifestItem[], depUrl: DepUrl) {
  const slug = starterSlug(s);
  return {
    $schema: "https://ui.shadcn.com/schema/registry-item.json",
    name: `starter-${slug}`,
    type: "registry:base",
    title: "Fluid Functionalism starter",
    description: `A Next.js app with every Fluid Functionalism component installed and these settings applied: ${describeSettings(s)}.`,
    docs: `Every component is in components/ui. Edit app/page.tsx to start, components/providers.tsx to change the defaults. Docs: ${SITE}/docs`,
    config: {
      style: s.base === "base" ? "base-nova" : "radix-nova",
      iconLibrary: "lucide",
      registries: { "@fluid": `${SITE}/r/{name}.json` },
    },
    dependencies: ["next-themes", "motion"],
    registryDependencies: registryDepsFor(s, items, depUrl),
    cssVars: { theme: RADIUS_SCALE },
    files: starterFiles(s),
  };
}

export function buildSetupItem(s: StarterSettings, items: readonly ManifestItem[], depUrl: DepUrl) {
  const slug = starterSlug(s);
  return {
    $schema: "https://ui.shadcn.com/schema/registry-item.json",
    name: `setup-${slug}`,
    type: "registry:item",
    title: "Fluid Functionalism setup",
    description: `Every Fluid Functionalism component, plus a FluidRoot wrapper with these settings: ${describeSettings(s)}.`,
    docs: `Wrap the root layout's children in <FluidRoot> from components/fluid-root.tsx, and load Inter with axes: ["opsz"]. Docs: ${SITE}/docs`,
    dependencies: ["motion"],
    registryDependencies: registryDepsFor(s, items, depUrl),
    files: setupFiles(s),
  };
}
