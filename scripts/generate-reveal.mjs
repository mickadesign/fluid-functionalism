/**
 * Generates both copies of the reveal CSS from one rule list:
 *
 *  1. the block between the <generated:reveal> markers in app/globals.css
 *  2. the `css` of the `reveal` item in registry.json
 *
 * Preset values come from lib/reveal/presets.ts. Each preset's spring tier
 * (slow for landing, moderate for product) is written as CSS linear() by
 * motion's own spring generator into --reveal-motion.
 *
 * `node scripts/generate-reveal.mjs` writes; `--check` exits non-zero when
 * either copy is stale (run by tests/reveal.test.ts).
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { spring as springGenerator } from "motion";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const GLOBALS_PATH = `${ROOT}app/globals.css`;
const REGISTRY_PATH = `${ROOT}registry.json`;
const START = "/* <generated:reveal> */";
const END = "/* </generated:reveal> */";

const load = async (path) => import(`${pathToFileURL(`${ROOT}${path}`).href}?t=${Date.now()}`);

/** A spring tier as CSS: "250ms linear(0, …, 1)". */
export function springCss(tier) {
  return springGenerator({
    duration: tier.duration * 1000,
    bounce: tier.bounce,
    keyframes: [0, 1],
  }).toString();
}

/** The whole reveal stylesheet as an ordered list: a string is a comment,
 *  [selector, declarations] a rule, [at-rule, list] a nested block. */
export function revealRules(presets, springs) {
  // Each preset sets --reveal-motion; outside one (.reveal-items or
  // .reveal-swap beside a preset) the helpers move like the product.
  const ease = `var(--reveal-motion, ${springs.moderate})`;
  const L = ":is(.reveal-landing, .reveal-landing-subtle)";
  const P = ":is(.reveal-product, .reveal-product-subtle)";
  const ENTER = "entry var(--reveal-scroll-start) entry var(--reveal-scroll)";
  const LEAVE = "exit calc(100% - var(--reveal-scroll)) exit calc(100% - var(--reveal-scroll-start))";
  const NENTER = "entry calc(var(--reveal-scroll-start) + var(--reveal-scroll) / 2) entry calc(var(--reveal-scroll) * 1.5)";
  const NLEAVE = "exit calc(100% - var(--reveal-scroll) * 1.5) exit calc(100% - var(--reveal-scroll-start) - var(--reveal-scroll) / 2)";
  const SKELETON = `:is(.reveal-product, .reveal-product-subtle, .reveal-items, .reveal-swap) [data-slot="skeleton"]`;
  const productStep = `${presets["reveal-product"].step}s`;

  const presetVars = (p) => {
    const v = { "--reveal-motion": springs[p.spring] };
    if (p.distance !== undefined) v["--reveal-distance"] = `${p.distance}px`;
    if (p.scale !== undefined) v["--reveal-scale"] = String(p.scale);
    v["--reveal-step"] = `${p.step}s`;
    if (p.scrollStart !== undefined) v["--reveal-scroll-start"] = `${p.scrollStart}px`;
    if (p.scroll !== undefined) v["--reveal-scroll"] = `${p.scroll}px`;
    return v;
  };
  const ladder = (selectors, from, to, delay) => {
    const out = [];
    for (let k = from; k <= to; k++) {
      const nth = k === to ? `:nth-child(n + ${k})` : `:nth-child(${k})`;
      out.push([selectors.map((s) => `${s}${nth}`).join(", "), delay(k - 1)]);
    }
    return out;
  };

  return [
    `── reveal presets — 1 class on a page's container, like scroll-fade ───────
   Generated by scripts/generate-reveal.mjs from lib/reveal/presets.ts; edit
   those, not this block.
   \`.reveal-landing\`: a page read once. The 1st child is the hero: its
   children rise and scale in on first paint, a step apart. Every later child
   is a section that does the same with the scroll, and leaves the same way
   at the top. \`.reveal-scroll\` makes a deeper element (a grid card) a
   section of its own. Browsers without view timelines show sections still.
   \`.reveal-product\`: the app itself. Every child fades in once on first
   paint, a short step apart; nothing moves on scroll. Slow data uses
   \`.reveal-swap\` and \`.reveal-items\`. \`-subtle\` tones each down.
   Landing steps ride spring.slow and product steps spring.moderate, written
   as linear() in --reveal-motion; only the \`from\` frame is set, so each
   block lands on its own styles.`,
    ["@keyframes reveal-preset", { from: { opacity: "0", transform: "translateY(var(--reveal-distance, 0px)) scale(var(--reveal-scale, 1))" } }],
    ...Object.entries(presets).map(([name, p]) => [`.${name}`, presetVars(p)]),
    [`${L} > :first-child > *, ${P} > *, .reveal-items > *, .reveal-swap > :last-child:not(:first-child)`, { animation: `reveal-preset ${ease} both` }],
    ...ladder([`${L} > :first-child > `, `${P} > `], 2, 4, (i) => ({
      "animation-delay": i === 1 ? "var(--reveal-step)" : `calc(var(--reveal-step) * ${i})`,
    })),
    [`${P} > .reveal-items`, { animation: "none" }],
    `\`.reveal-items\`: the block stays still and its children arrive one by one,
   a step apart for 8 steps. Inside a preset it takes the preset's step;
   anywhere else (a sidebar beside the preset) it uses the product's.`,
    ...ladder([".reveal-items > "], 2, 8, (i) => ({ "animation-delay": `calc(var(--reveal-step, ${productStep}) * ${i})` })),
    `\`.reveal-swap\`: a skeleton and the block it stands in for, stacked in 1
   cell. Add the real block after the skeleton when the data lands: the
   skeleton fades out as the block fades in, so the space is never empty.
   With \`.reveal-items\` on both, each row hands over to its real row.`,
    ["@keyframes reveal-out", { to: { opacity: "0" } }],
    [".reveal-swap", { display: "grid" }],
    [".reveal-swap > *", { "grid-area": "1 / 1", "min-width": "0" }],
    [".reveal-swap > :first-child:not(:last-child)", { "pointer-events": "none", animation: `reveal-out ${ease} forwards` }],
    [".reveal-swap > .reveal-items:not(:only-child)", { animation: "none" }],
    [".reveal-swap > .reveal-items:first-child:not(:last-child) > *", { "animation-name": "reveal-out", "animation-fill-mode": "forwards" }],
    `Skeletons fade in over the slow tier's 250ms on an even curve, then pulse
   like shadcn's \`animate-pulse\`, on keyframes of their own so the block
   works without Tailwind's. A skeleton that has been swapped out stops
   pulsing: it is fading away and would otherwise animate unseen forever.`,
    ["@keyframes reveal-skeleton-in", { from: { opacity: "0" } }],
    ["@keyframes reveal-pulse", { "50%": { opacity: "0.5" } }],
    [SKELETON, { animation: "reveal-skeleton-in 250ms ease-in-out both, reveal-pulse 2s cubic-bezier(0.4, 0, 0.6, 1) 250ms infinite" }],
    [`.reveal-swap > :first-child:not(:last-child) [data-slot="skeleton"]`, { animation: "none" }],
    `Leaving at the top mirrors the way in: it fades out, lifts, and scales down.`,
    ["@keyframes reveal-leave", { to: { opacity: "0", transform: "translateY(calc(var(--reveal-distance, 0px) * -1)) scale(var(--reveal-scale, 1))" } }],
    ["@supports (animation-timeline: view())", [
      `Scroll sections, and any \`.reveal-scroll\` deeper in, rise in with the
     scroll and leave the same way at the top. They also play a load step
     after the hero, so one already on screen at first paint arrives with the
     page; off screen, that step plays unseen and the scroll takes over.`,
      [`${L} > :first-child`, { animation: "reveal-leave 1ms linear both", "animation-timeline": "view()", "animation-range": LEAVE }],
      [`${L} > :not(:first-child), ${L} .reveal-scroll`, {
        "--reveal-load-delay": "calc(var(--reveal-step) * 4)",
        animation: `reveal-preset 1ms linear both, reveal-leave 1ms linear both, reveal-preset ${ease} backwards`,
        "animation-timeline": "view(), view(), auto",
        "animation-range": `${ENTER}, ${LEAVE}, normal`,
        "animation-delay": "0s, 0s, var(--reveal-load-delay)",
      }],
      ...ladder([`${L} .reveal-scroll`], 2, 4, (i) => ({ "--reveal-load-delay": `calc(var(--reveal-step) * ${4 + i})` })),
      `The section holding \`.reveal-scroll\` elements stays still, so nothing
     animates twice.`,
      [`${L} > :not(:first-child):has(.reveal-scroll)`, { animation: "none" }],
      `A \`.reveal-scroll\` inside another one follows it: half a range later on
     the way in, half a range sooner on the way out, a step later on load.`,
      [`${L} .reveal-scroll .reveal-scroll`, {
        "--reveal-load-delay": "inherit",
        "animation-range": `${NENTER}, ${NLEAVE}, normal`,
        "animation-delay": "0s, 0s, calc(var(--reveal-load-delay) + var(--reveal-step))",
      }],
    ]],
    ["@media (prefers-reduced-motion: reduce)", [
      `Reduced motion keeps the fades and drops the rest: no rise, no scale, no
     scroll motion, no pulse.`,
      [L, { "--reveal-distance": "0px", "--reveal-scale": "1" }],
      [`${L} > :first-child, ${L} > :not(:first-child):has(.reveal-scroll)`, { animation: "none" }],
      [`${L} > :not(:first-child), ${L} .reveal-scroll`, { animation: `reveal-preset ${ease} backwards`, "animation-delay": "var(--reveal-load-delay, 0s)" }],
      // Matches the nested rule's specificity, so nested content keeps its
      // step after its card instead of taking that rule's 3-value list.
      [`${L} .reveal-scroll .reveal-scroll`, { "animation-delay": "calc(var(--reveal-load-delay, 0s) + var(--reveal-step))" }],
      [SKELETON, { animation: "reveal-skeleton-in 250ms ease-in-out both" }],
    ]],
  ];
}

/** Split on top-level commas only (not inside parentheses). */
function splitTop(value) {
  const parts = [];
  let depth = 0;
  let cur = "";
  for (const ch of value) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      parts.push(cur.trim());
      cur = "";
    } else cur += ch;
  }
  parts.push(cur.trim());
  return parts;
}

function renderDecls(decls, pad) {
  return Object.entries(decls).map(([k, v]) => {
    if (typeof v === "object") {
      return `${pad}${k} {\n${renderDecls(v, pad + "  ")}\n${pad}}`;
    }
    const parts = k.startsWith("animation") ? splitTop(v) : [v];
    if (parts.length > 1 && k === "animation") {
      return `${pad}${k}:\n${parts.map((p) => `${pad}  ${p}`).join(",\n")};`;
    }
    return `${pad}${k}: ${v};`;
  }).join("\n");
}

export function renderCss(rules, pad = "") {
  return rules.map((entry) => {
    if (typeof entry === "string") return `${pad}/* ${entry} */`;
    const [selector, body] = entry;
    if (Array.isArray(body)) return `${selector} {\n${renderCss(body, pad + "  ")}\n${pad}}`;
    const sel = selector.startsWith("@") ? selector : splitTop(selector).join(`,\n${pad}`);
    return `${pad}${sel} {\n${renderDecls(body, pad + "  ")}\n${pad}}`;
  }).join("\n");
}

export function registryCss(rules) {
  const out = {};
  for (const entry of rules) {
    if (typeof entry === "string") continue;
    const [selector, body] = entry;
    out[selector] = Array.isArray(body) ? registryCss(body) : body;
  }
  return out;
}

export async function generate({ write = false } = {}) {
  const [{ revealPresets }, { spring }] = await Promise.all([
    load("lib/reveal/presets.ts"),
    load("registry/default/lib/springs.ts"),
  ]);
  const rules = revealRules(revealPresets, {
    slow: springCss(spring.slow),
    moderate: springCss(spring.moderate),
  });

  const globals = readFileSync(GLOBALS_PATH, "utf8");
  const a = globals.indexOf(START);
  const b = globals.indexOf(END);
  if (a === -1 || b === -1 || b < a) throw new Error(`Markers ${START} … ${END} missing in app/globals.css`);
  const nextGlobals = `${globals.slice(0, a + START.length)}\n${renderCss(rules)}\n${globals.slice(b)}`;

  const registryText = readFileSync(REGISTRY_PATH, "utf8");
  const registry = JSON.parse(registryText);
  const item = registry.items.find((i) => i.name === "reveal");
  item.css = registryCss(rules);
  const nextRegistry = `${JSON.stringify(registry, null, 2)}\n`;

  if (write) {
    writeFileSync(GLOBALS_PATH, nextGlobals);
    writeFileSync(REGISTRY_PATH, nextRegistry);
  }
  return {
    "app/globals.css": [globals, nextGlobals],
    "registry.json": [registryText, nextRegistry],
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes("--check");
  const files = await generate({ write: !check });
  const stale = Object.entries(files).filter(([, [x, y]]) => x !== y).map(([p]) => p);
  if (check && stale.length) {
    console.error(`Stale: ${stale.join(", ")}. Run \`node scripts/generate-reveal.mjs\`.`);
    process.exit(1);
  }
  if (!check) console.log(stale.length ? `wrote ${stale.join(", ")}` : "reveal CSS up to date");
}
