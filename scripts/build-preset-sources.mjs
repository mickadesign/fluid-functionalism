// The DataTable preset's install ships two helper files as they are on the
// site (the saved views' tabs, the undo toast), so an install has the same
// parts the playground runs. The generator needs their text on the server
// and in the browser (the Copy prompt lists the files), so it is kept as
// strings in a generated module.
//
//   node scripts/build-preset-sources.mjs          write the module
//   node scripts/build-preset-sources.mjs --check  fail if it is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCES = {
  VIEW_TABS_SOURCE: "lib/docs/playgrounds/view-tabs.tsx",
  UNDO_TOAST_SOURCE: "lib/docs/undo-toast.tsx",
  NEW_ITEM_DIALOG_SOURCE: "lib/docs/playgrounds/new-item-dialog.tsx",
};
const out = join(root, "lib/preset/data-table-sources.generated.ts");

const body =
  "// Generated by scripts/build-preset-sources.mjs. Do not edit: change the\n" +
  "// source file and run `npm run preset:sources`.\n\n" +
  Object.entries(SOURCES)
    .map(
      ([name, file]) =>
        `/** ${file}, as text. */\nexport const ${name} = ${JSON.stringify(readFileSync(join(root, file), "utf8"))};\n`
    )
    .join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== body) {
    console.error("lib/preset/data-table-sources.generated.ts is stale: run `npm run preset:sources`.");
    process.exit(1);
  }
} else {
  writeFileSync(out, body);
  console.log(`wrote ${Object.keys(SOURCES).length} sources to ${out}`);
}
